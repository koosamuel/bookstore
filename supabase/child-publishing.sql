-- 기존 빙고서점 도서는 계속 공개되도록 최초 1회 보정합니다.
update public.books
set publication_status = 'published', guardian_consent = 'approved'
where publication_status = 'draft'
  and id in ('B001','B002','B003','B004','B005','B006')
  and page_count = 0
  and published_at is null;

create unique index if not exists books_slug_unique
on public.books (slug) where slug is not null;

create table if not exists public.book_episodes (
  id bigint generated by default as identity primary key,
  book_id text not null references public.books(id) on update cascade on delete cascade,
  episode_number integer not null check (episode_number > 0),
  title text not null,
  start_page integer not null check (start_page > 0),
  end_page integer not null check (end_page >= start_page),
  estimated_panel_count integer not null default 0 check (estimated_panel_count >= 0),
  summary text not null default '',
  keywords text[] not null default '{}',
  display_order integer not null default 0,
  status text not null default 'draft'
    check (status in ('draft', 'review', 'approved', 'published')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (book_id, episode_number)
);

create table if not exists public.book_pages (
  id bigint generated by default as identity primary key,
  book_id text not null references public.books(id) on update cascade on delete cascade,
  episode_id bigint references public.book_episodes(id) on delete set null,
  page_number integer not null check (page_number > 0),
  panel_count integer not null default 0 check (panel_count >= 0),
  original_path text,
  public_image_url text,
  ocr_draft text not null default '',
  transcript text not null default '',
  privacy_flag boolean not null default false,
  content_flag boolean not null default false,
  review_status text not null default 'draft'
    check (review_status in ('draft', 'review', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (book_id, page_number)
);

-- 원본 페이지를 훼손하지 않고 에피소드별 웹툰 컷과 읽는 순서를 관리합니다.
create table if not exists public.book_panels (
  id bigint generated by default as identity primary key,
  episode_id bigint not null references public.book_episodes(id) on delete cascade,
  page_id bigint references public.book_pages(id) on delete set null,
  panel_number integer not null check (panel_number > 0),
  display_order integer not null default 0,
  crop_x numeric(8,5) not null default 0 check (crop_x >= 0 and crop_x <= 1),
  crop_y numeric(8,5) not null default 0 check (crop_y >= 0 and crop_y <= 1),
  crop_width numeric(8,5) not null default 1 check (crop_width > 0 and crop_width <= 1),
  crop_height numeric(8,5) not null default 1 check (crop_height > 0 and crop_height <= 1),
  source_asset_path text,
  public_asset_url text,
  gap_after text not null default 'medium'
    check (gap_after in ('small', 'medium', 'large')),
  transcript text not null default '',
  privacy_flag boolean not null default false,
  content_flag boolean not null default false,
  status text not null default 'draft'
    check (status in ('draft', 'review', 'approved', 'published', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint book_panels_crop_within_source check (
    crop_x + crop_width <= 1 and crop_y + crop_height <= 1
  ),
  unique (episode_id, panel_number)
);

create table if not exists public.ai_suggestions (
  id bigint generated by default as identity primary key,
  book_id text not null references public.books(id) on update cascade on delete cascade,
  page_id bigint references public.book_pages(id) on delete set null,
  episode_id bigint references public.book_episodes(id) on delete set null,
  suggestion_type text not null
    check (suggestion_type in ('editing', 'summary', 'metadata', 'promotion', 'translation', 'safety')),
  source_version text not null default '',
  input_text text not null,
  output_text text not null,
  status text not null default 'draft'
    check (status in ('draft', 'accepted', 'rejected', 'revised')),
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create table if not exists public.publication_reviews (
  id bigint generated by default as identity primary key,
  book_id text not null references public.books(id) on update cascade on delete cascade,
  review_type text not null
    check (review_type in ('privacy', 'content', 'copyright', 'guardian')),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'changes_requested', 'rejected')),
  notes text not null default '',
  reviewed_by uuid default auth.uid(),
  reviewed_at timestamptz,
  unique (book_id, review_type)
);

create table if not exists public.publication_assets (
  id bigint generated by default as identity primary key,
  book_id text not null references public.books(id) on update cascade on delete cascade,
  asset_type text not null
    check (asset_type in ('cover', 'thumbnail', 'page', 'preview_pdf')),
  storage_path text not null,
  is_public boolean not null default false,
  approved_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists book_episodes_book_order_idx on public.book_episodes(book_id, display_order, episode_number);
create index if not exists book_pages_book_page_idx on public.book_pages(book_id, page_number);
create index if not exists book_panels_episode_order_idx on public.book_panels(episode_id, display_order, panel_number);
create index if not exists ai_suggestions_book_created_idx on public.ai_suggestions(book_id, created_at desc);
create index if not exists publication_reviews_book_idx on public.publication_reviews(book_id);

