-- 공개 독자는 승인·공개된 정보만 읽고, 운영자는 작업 데이터를 관리합니다.
drop policy if exists "books are publicly readable" on public.books;
drop policy if exists "published books are publicly readable" on public.books;
drop policy if exists "operators can read all books" on public.books;
create policy "published books are publicly readable"
on public.books for select to anon
using (publication_status = 'published');
create policy "operators can read all books"
on public.books for select to authenticated
using (true);

drop policy if exists "published episodes are publicly readable" on public.book_episodes;
drop policy if exists "operators manage episodes" on public.book_episodes;
create policy "published episodes are publicly readable"
on public.book_episodes for select to anon
using (status = 'published' and exists (
  select 1 from public.books b where b.id = book_id and b.publication_status = 'published'
));
create policy "operators manage episodes"
on public.book_episodes for all to authenticated using (true) with check (true);

drop policy if exists "operators manage pages" on public.book_pages;
create policy "operators manage pages"
on public.book_pages for all to authenticated using (true) with check (true);

drop policy if exists "published panels are publicly readable" on public.book_panels;
drop policy if exists "operators manage panels" on public.book_panels;
create policy "published panels are publicly readable"
on public.book_panels for select to anon
using (status = 'published' and exists (
  select 1
  from public.book_episodes e
  join public.books b on b.id = e.book_id
  where e.id = episode_id
    and e.status = 'published'
    and b.publication_status = 'published'
));
create policy "operators manage panels"
on public.book_panels for all to authenticated using (true) with check (true);

drop policy if exists "operators manage ai suggestions" on public.ai_suggestions;
drop policy if exists "operators manage publication reviews" on public.publication_reviews;
drop policy if exists "operators manage publication assets" on public.publication_assets;
create policy "operators manage ai suggestions"
on public.ai_suggestions for all to authenticated using (true) with check (true);
create policy "operators manage publication reviews"
on public.publication_reviews for all to authenticated using (true) with check (true);
create policy "operators manage publication assets"
on public.publication_assets for all to authenticated using (true) with check (true);

