create or replace function public.submit_book_comment(
  p_book_id text,
  p_body text,
  p_reader_label text default '승인 독자'
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_comment_id bigint;
  clean_body text := btrim(coalesce(p_body, ''));
  clean_label text := '승인 독자';
begin
  if auth.uid() is null then
    raise exception 'authentication required';
  end if;

  if not exists (
    select 1
    from public.books b
    join public.book_engagement_settings s on s.book_id = b.id
    where b.id = p_book_id
      and b.publication_status = 'published'
      and s.comments_enabled
  ) then
    raise exception 'comments are unavailable';
  end if;

  if (
    select count(*)
    from public.book_comments
    where created_by = auth.uid() and created_at > now() - interval '10 minutes'
  ) >= 3 then
    raise exception 'comment rate limit exceeded';
  end if;

  insert into public.book_comments (book_id, created_by, reader_label, body, status)
  values (p_book_id, auth.uid(), clean_label, clean_body, 'pending')
  returning id into new_comment_id;

  return new_comment_id;
end;
$$;

revoke all on function public.submit_book_comment(text, text, text) from public;
grant execute on function public.submit_book_comment(text, text, text) to authenticated;

create or replace function public.record_book_view(
  p_book_id text,
  p_session_hash text,
  p_completed boolean default false
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_view_date date := (timezone('Asia/Seoul', now()))::date;
begin
  if char_length(coalesce(p_session_hash, '')) not between 20 and 100 then
    raise exception 'invalid anonymous session';
  end if;

  if not exists (
    select 1 from public.books
    where id = p_book_id and publication_status = 'published'
  ) then
    raise exception 'book is not published';
  end if;

  insert into public.book_view_events
    (book_id, anonymous_session_hash, view_date, completed_at)
  values
    (p_book_id, p_session_hash, current_view_date, case when p_completed then now() else null end)
  on conflict (book_id, anonymous_session_hash, view_date)
  do update set completed_at = case
    when excluded.completed_at is not null
      then coalesce(public.book_view_events.completed_at, excluded.completed_at)
    else public.book_view_events.completed_at
  end;

  insert into public.book_metrics_daily
    (metric_date, book_id, unique_views, completions, updated_at)
  select
    current_view_date,
    p_book_id,
    count(*)::integer,
    count(*) filter (where completed_at is not null)::integer,
    now()
  from public.book_view_events
  where book_id = p_book_id and view_date = current_view_date
  on conflict (metric_date, book_id)
  do update set
    unique_views = excluded.unique_views,
    completions = excluded.completions,
    updated_at = now();
end;
$$;

revoke all on function public.record_book_view(text, text, boolean) from public;
grant execute on function public.record_book_view(text, text, boolean) to anon, authenticated;

create or replace view public.book_engagement_totals
with (security_invoker = true)
as
with metric_totals as (
  select
    book_id,
    sum(unique_views)::bigint as unique_views,
    sum(completions)::bigint as completions
  from public.book_metrics_daily
  group by book_id
), comment_totals as (
  select book_id, count(*)::bigint as approved_comments
  from public.book_comments
  where status = 'approved'
  group by book_id
)
select
  b.id as book_id,
  coalesce(m.unique_views, 0)::bigint as unique_views,
  coalesce(m.completions, 0)::bigint as completions,
  coalesce(c.approved_comments, 0)::bigint as approved_comments,
  (coalesce(m.unique_views, 0) + coalesce(m.completions, 0) * 2)::bigint as ranking_score
from public.books b
left join metric_totals m on m.book_id = b.id
left join comment_totals c on c.book_id = b.id
join public.book_engagement_settings s on s.book_id = b.id
where b.publication_status = 'published' and s.ranking_enabled;

grant select on public.book_engagement_totals to anon, authenticated;

do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='book_comments') then
    alter publication supabase_realtime add table public.book_comments;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='book_metrics_daily') then
    alter publication supabase_realtime add table public.book_metrics_daily;
  end if;
end $$;

