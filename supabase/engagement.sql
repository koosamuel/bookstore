create table if not exists public.book_view_events (
  id bigint generated by default as identity primary key,
  book_id text not null references public.books(id) on update cascade on delete cascade,
  anonymous_session_hash text not null check (char_length(anonymous_session_hash) between 20 and 100),
  view_date date not null default ((timezone('Asia/Seoul', now()))::date),
  viewed_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (book_id, anonymous_session_hash, view_date)
);

create table if not exists public.book_metrics_daily (
  metric_date date not null,
  book_id text not null references public.books(id) on update cascade on delete cascade,
  unique_views integer not null default 0 check (unique_views >= 0),
  completions integer not null default 0 check (completions >= 0),
  updated_at timestamptz not null default now(),
  primary key (metric_date, book_id)
);

create table if not exists public.book_comments (
  id bigint generated by default as identity primary key,
  book_id text not null references public.books(id) on update cascade on delete cascade,
  episode_id bigint references public.book_episodes(id) on delete set null,
  created_by uuid not null default auth.uid(),
  reader_label text not null default '승인 독자' check (char_length(reader_label) between 2 and 30),
  body text not null check (
    char_length(btrim(body)) between 2 and 300
    and body !~ '[<>]'
    and body !~* '(https?://|www\.)'
    and body !~* '[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}'
    and body !~ '(^|[^0-9])0[0-9]{1,2}[- .]?[0-9]{3,4}[- .]?[0-9]{4}([^0-9]|$)'
  ),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'hidden')),
  moderation_flags text[] not null default '{}',
  reviewed_by uuid,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.book_engagement_settings (
  book_id text primary key references public.books(id) on update cascade on delete cascade,
  comments_enabled boolean not null default true,
  ranking_enabled boolean not null default true,
  guardian_approved_at timestamptz,
  updated_at timestamptz not null default now()
);

insert into public.book_engagement_settings (book_id, comments_enabled, ranking_enabled, guardian_approved_at)
select id, true, true, case when guardian_consent = 'approved' then now() else null end
from public.books
on conflict (book_id) do nothing;

create index if not exists book_view_events_book_date_idx
on public.book_view_events(book_id, view_date);
create index if not exists book_comments_book_status_created_idx
on public.book_comments(book_id, status, created_at desc);
create index if not exists book_comments_pending_idx
on public.book_comments(created_at) where status = 'pending';

alter table public.book_view_events enable row level security;
alter table public.book_metrics_daily enable row level security;
alter table public.book_comments enable row level security;
alter table public.book_engagement_settings enable row level security;

